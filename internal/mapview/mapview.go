// Package mapview renders `ekumen map`: one self-contained HTML file with
// the lead's inbox, the task graph and the decided list (C-cli-json §2).
// It is a Go port of tools/map-prototype. All data (statuses, priorities,
// edges) is computed by the CLI; the page only lays the graph out, with
// dagre 0.8.5 (MIT, assets/dagre.LICENSE) inlined so it works offline.
package mapview

import (
	_ "embed"
	"encoding/json"
	"strings"

	"github.com/Yashswarnkar/ekumen/internal/project"
)

//go:embed template.html
var tmpl string

//go:embed assets/dagre.min.js
var dagreJS string

//go:embed assets/dagre.LICENSE
var dagreLicense string

// Data is what the page renders: the same data as `ekumen graph` and
// `ekumen inbox --for lead`, plus tasks and decisions for details.
type Data struct {
	GeneratedAt string              `json:"generated_at"`
	Commit      string              `json:"commit"`
	Project     string              `json:"project"`
	Observed    bool                `json:"observed"`
	Counts      project.StateCounts `json:"counts"`
	Inbox       []project.InboxItem `json:"inbox"`
	Nodes       []project.Node      `json:"nodes"`
	Edges       []project.Edge      `json:"edges"`
	Tasks       []project.Task      `json:"tasks"`
	Decisions   []project.Decision  `json:"decisions"`
	// Links maps an item id to its source files on the git host (see
	// LinkBase). Empty when no link base is known: the page then shows
	// plain text.
	Links map[string]Link `json:"links"`
}

// Link is where an item's full text lives.
type Link struct {
	// Source is the item's own file: a decision's YAML, a task's brief,
	// a contract's body.
	Source string `json:"source,omitempty"`
	// Handoff is a task's latest handoff file.
	Handoff string `json:"handoff,omitempty"`
}

// Render returns the HTML page for d.
func Render(d Data) ([]byte, error) { return render(tmpl, d) }

// RenderFragment returns the page without the <!doctype>, <html>, <head>
// and <body> wrappers, for embedding in another page (`ekumen map
// --fragment`). The template scopes every style rule to the wrapping
// <div class="ekumen-map">, has no element ids (the script looks elements
// up inside its own wrapper, and SVG marker ids are unique per render), so
// nothing leaks into the host page.
func RenderFragment(d Data) ([]byte, error) { return render(fragmentOf(tmpl), d) }

func render(t string, d Data) ([]byte, error) {
	if d.Links == nil {
		d.Links = map[string]Link{}
	}
	b, err := json.Marshal(d)
	if err != nil {
		return nil, err
	}
	// Keep the JSON from closing the script element or starting a comment.
	js := strings.NewReplacer("</", `<\/`, "<!--", `<\!--`).Replace(string(b))
	lib := "/*! dagre 0.8.5 | " + strings.Join(strings.Fields(dagreLicense), " ") + " */\n" + dagreJS
	page := strings.Replace(t, "/*DAGRE*/", lib, 1)
	page = strings.Replace(page, "/*DATA*/null", js, 1)
	return []byte(page), nil
}

// fragmentOf cuts the template down to its scoped styles and the
// contents of <body> (the <div class="ekumen-map"> wrapper and its
// scripts). The page-only style block, for the document body, is dropped.
func fragmentOf(page string) string {
	style := ""
	if i, j := strings.Index(page, "<style>"), strings.Index(page, "</style>"); i >= 0 && j > i {
		style = page[i : j+len("</style>")]
	}
	body := page
	if i := strings.Index(page, "<body>"); i >= 0 {
		body = body[i+len("<body>"):]
	}
	if j := strings.LastIndex(body, "</body>"); j >= 0 {
		body = body[:j]
	}
	return "<!-- Generated by `ekumen map --fragment`. Self-contained: no network requests. Graph layout by dagre 0.8.5 (MIT). -->\n" +
		style + "\n" + strings.TrimSpace(body) + "\n"
}
